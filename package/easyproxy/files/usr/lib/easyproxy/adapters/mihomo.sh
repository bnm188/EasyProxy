#!/bin/sh
# mihomo (Clash.Meta) engine contract.
#
# Same verbs as adapters/sing-box.sh, so the CLI and init script never branch on
# an engine name:
#
#   mihomo_available    exit 0 when the binary can be executed
#   mihomo_version      version line of the binary
#   mihomo_config       path of the YAML config it consumes
#   mihomo_validate     run `mihomo -t`, which parses the config and exits
#   mihomo_check        alias of mihomo_validate
#   mihomo_run          exec the engine in the foreground (procd supervises)
#   mihomo_home         working directory (-d), where geodata lives
#
# Configuration is generated by usr/lib/easyproxy/mihomo.sh, not here: the
# adapter stays a thin process wrapper, exactly like sing-box's.

mihomo_binary() {
	local value
	value="$(uci -q get easyproxy.mihomo.binary 2>/dev/null)"
	printf '%s' "${value:-/usr/bin/mihomo}"
}

mihomo_config() {
	local value
	value="$(uci -q get easyproxy.mihomo.config_file 2>/dev/null)"
	printf '%s' "${value:-/etc/easyproxy/mihomo.yaml}"
}

mihomo_home() {
	local value
	value="$(uci -q get easyproxy.mihomo.home 2>/dev/null)"
	printf '%s' "${value:-/etc/easyproxy/mihomo}"
}

mihomo_available() {
	local binary
	binary="$(mihomo_binary)"
	[ -n "$binary" ] && [ -x "$binary" ]
}

mihomo_version() {
	local binary
	binary="$(mihomo_binary)"
	mihomo_available || return 1
	"$binary" -v 2>/dev/null | head -n 1
}

mihomo_validate() {
	local binary cfg home
	binary="$(mihomo_binary)"
	cfg="$(mihomo_config)"
	home="$(mihomo_home)"
	[ -r "$cfg" ] || { echo "EasyProxy: config file missing: $cfg" >&2; return 1; }
	[ -x "$binary" ] || { echo "EasyProxy: binary missing: $binary" >&2; return 1; }
	mkdir -p "$home" 2>/dev/null
	"$binary" -t -f "$cfg" -d "$home" >/dev/null 2>&1
}

mihomo_check() {
	mihomo_validate
}

mihomo_run() {
	local binary cfg home
	binary="$(mihomo_binary)"
	cfg="$(mihomo_config)"
	home="$(mihomo_home)"
	[ -x "$binary" ] || { echo "EasyProxy: binary missing: $binary" >&2; return 1; }
	mkdir -p "$home" 2>/dev/null
	exec "$binary" -f "$cfg" -d "$home"
}
